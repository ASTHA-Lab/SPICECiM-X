"""
Array-level I-V characterisation table for SPICECiM-X.

Where ``CellITable`` describes one isolated 1T1R cell, ``ArrayCharTable``
describes the full subarray — the 1T1R cell plus everything between the
external VI source and the cell terminal (BL_DRIVER pass gate, wire R, SL
return path).  The table is keyed by ``(N, T_uniform, V_input)`` where N
is the subarray size, T_uniform is the (shared) filament thickness of
every cell during characterisation, and V_input is the (shared) input
voltage applied to every BL.  The recorded quantity is the per-column
bit-line current — under uniform conditions every column reads
identically, so a single iprobe per characterisation suffices.

The table is generated by ``spicecimx.sim.array_char_run`` at exactly
TWO subarray sizes (configured by ``sim.array_char_size_primary`` and
``sim.array_char_size_secondary``).  For any subarray size between (or
modestly outside) those two anchors, inference-time lookups linearly
interpolate the I-V surface in N.  This is the natural axis for the
dominant array non-ideality — BL_DRIVER pass-gate IR drop scales with
the total row current, which scales with N — so a two-point linear fit
captures it cleanly without retaining a parametric loading model.

V-linearization curve h_array(V)
--------------------------------
The single most useful derived product is the array V-nonlinearity curve

    h_array(V) = I_col(V, T_ref, N) / G0_array(T_ref, N)

where ``G0_array(T_ref, N) = dI_col/dV |_{V→0}`` is the array's V→0
column conductance at reference T.  This is the same construction as
``CellITable.build_v_linearization`` but at the array level — it
captures BOTH cell I-V nonlinearity (the cell's intrinsic super-linear
I-V) and array loading (BL_DRIVER drop reduces V at each cell as more
columns load the row).  Driving the array at ``V_phys = h_array⁻¹(V_target)``
makes the column current track ``G0_array · V_target`` to within ~0.5%
across the T range — the residual being the T-dependence of h_array.

All three backends consume the same h_array curve:
  * fastdc  — applies h⁻¹ on V before its per-cell table lookup;
  * dc      — applies h⁻¹ before deck emission so Spectre sees V_phys;
  * transient — applies h⁻¹ to the PWL waveform amplitudes.

The forward simulation each backend does next is unchanged.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Optional

import numpy as np


# ---------------------------------------------------------------------------
# Container
# ---------------------------------------------------------------------------
@dataclass
class ArrayCharTable:
    """
    Two-anchor array I-V table.

    Attributes
    ----------
    T_grid
        (nT,) filament thicknesses in metres.  Shared across both anchor sizes.
    V_grid
        (nV,) BL input voltages in volts.  Shared across both anchor sizes.
    N_primary, N_secondary
        Anchor subarray sizes (square: N_primary x N_primary, etc.).
    I_primary, I_secondary
        (nT, nV) per-column bit-line currents at each anchor.  In amps.
        Sign convention: positive current sinking into VSS through IPRB
        (we store ``abs(...)`` so consumers don't have to think about it).
    config_hash
        Hex digest of all inputs that defined this characterisation —
        transistor model file + corner, memristor parameters, vdd, T/V
        grid, both anchor sizes, temperature.  Cache invalidation key.
    """
    T_grid:        np.ndarray
    V_grid:        np.ndarray
    N_primary:     int
    N_secondary:   int
    I_primary:     np.ndarray
    I_secondary:   np.ndarray
    config_hash:   str

    @property
    def nT(self) -> int: return len(self.T_grid)
    @property
    def nV(self) -> int: return len(self.V_grid)
    @property
    def T_min(self) -> float: return float(self.T_grid[0])
    @property
    def T_max(self) -> float: return float(self.T_grid[-1])
    @property
    def V_min(self) -> float: return float(self.V_grid[0])
    @property
    def V_max(self) -> float: return float(self.V_grid[-1])

    # ------------------------------------------------------------------ I/O
    def save_npz(self, path: str | Path) -> None:
        np.savez_compressed(
            str(path),
            T_grid=self.T_grid, V_grid=self.V_grid,
            N_primary=self.N_primary, N_secondary=self.N_secondary,
            I_primary=self.I_primary, I_secondary=self.I_secondary,
            config_hash=self.config_hash,
        )

    @classmethod
    def load_npz(cls, path: str | Path) -> "ArrayCharTable":
        d = np.load(str(path), allow_pickle=False)
        return cls(
            T_grid=d["T_grid"], V_grid=d["V_grid"],
            N_primary=int(d["N_primary"]), N_secondary=int(d["N_secondary"]),
            I_primary=d["I_primary"], I_secondary=d["I_secondary"],
            config_hash=str(d["config_hash"]),
        )

    # ------------------------------------------------ Cross-size interpolation
    def I_at(self, N: int) -> np.ndarray:
        """
        Return the (nT, nV) I-V surface at subarray size ``N`` by linear
        interpolation between the two anchors.  Extrapolation is allowed
        but should be kept within ~2x of the anchor range; for sizes far
        outside, the linear-in-N assumption breaks down and you should
        re-characterise.

        For N == N_primary or N == N_secondary, the corresponding anchor
        is returned exactly with no interpolation noise.
        """
        if N == self.N_primary:   return self.I_primary
        if N == self.N_secondary: return self.I_secondary
        # Linear in N: I_col scales roughly linearly with row-current
        # loading for fixed (T, V), so two-point extrapolation in N is a
        # solid first-order model.  (For exotic sizes a smarter fit could
        # use 1/(1 + N*G*R_p) but it requires a free R_p parameter.)
        alpha = (N - self.N_primary) / (self.N_secondary - self.N_primary)
        return (1.0 - alpha) * self.I_primary + alpha * self.I_secondary

    # ------------------------------------------------ V-linearisation curve
    def build_v_linearization(
        self,
        N: int,
        T_ref: Optional[float] = None,
        v_low: float = 0.05,
    ) -> "ArrayVLinearizer":
        """
        Build h_array(V) = I_col(T_ref, V, N) / G0_array(T_ref, N)
        — the array's V-nonlinearity curve at subarray size ``N``.

        Driving the array with ``V_phys = h_array⁻¹(V_target)`` produces
        a column current of ``G0_array(T_ref) · V_target`` (modulo T
        residuals) — exactly the linear-cell behaviour the affine demap
        expects.  See ``ArrayVLinearizer.inverse`` for the inverse map.

        Parameters
        ----------
        N
            Subarray size at which to build the linearizer.  The
            characterisation table is interpolated to this N first.
        T_ref
            Reference T for h.  Default: midpoint of the T grid.  The
            T-dependence residual is minimised when T_ref sits in the
            middle of the actual cell-T distribution at inference.
        v_low
            V at which to estimate the V→0 slope G0_array.  We use a
            small-but-not-zero V to avoid amplifying any numerical
            noise at the V=0 boundary; 0.05 V is in the linear region
            of every realistic cell.
        """
        I_N = self.I_at(N)                            # (nT, nV)
        if T_ref is None:
            T_ref = 0.5 * (self.T_min + self.T_max)
        # Find T_ref index by nearest-neighbour
        t_idx = int(np.argmin(np.abs(self.T_grid - T_ref)))
        I_row = np.abs(I_N[t_idx])                    # (nV,)  current at T_ref

        # G0_array = slope at V→0, estimated from I(V_low)/V_low.
        # The V grid may not have V=v_low exactly; interpolate.
        I_at_vlow = float(np.interp(v_low, self.V_grid, I_row))
        G0_array  = I_at_vlow / v_low                 # A/V

        # h_array(V) = I_col(V) / G0_array.  Pin h(0)=0 even if the V grid
        # doesn't include V=0 — h must pass through the origin physically.
        if self.V_grid[0] > 0:
            V_ext = np.concatenate(([0.0], self.V_grid))
            h_ext = np.concatenate(([0.0], I_row / G0_array))
        else:
            V_ext = self.V_grid.copy()
            h_ext = (I_row / G0_array).copy()

        # Enforce monotonicity (small numerical jitter near V=0 can break inv).
        h_ext = np.maximum.accumulate(h_ext)

        return ArrayVLinearizer(V_grid=V_ext, h=h_ext, N=N,
                                T_ref=float(self.T_grid[t_idx]),
                                G0_array=G0_array)


# ---------------------------------------------------------------------------
# V-linearizer
# ---------------------------------------------------------------------------
@dataclass
class ArrayVLinearizer:
    """
    Array-level voltage pre-warp.  Constructed by
    ``ArrayCharTable.build_v_linearization(N)``.

    ``inverse(V_target)`` returns the physical voltage to apply at the
    external VI source so that the array's column current matches the
    linear-cell prediction ``G0_array · V_target``.
    """
    V_grid:   np.ndarray   # (nV+1,) with V=0 prepended; h's domain
    h:        np.ndarray   # (nV+1,) h_array(V_grid)
    N:        int          # subarray size this linearizer was built for
    T_ref:    float        # reference T used to build h (metres)
    G0_array: float        # V→0 column conductance, A/V (informational)

    def forward(self, V: np.ndarray) -> np.ndarray:
        """h_array(V) — what the un-pre-warped cell would have produced."""
        return np.interp(V, self.V_grid, self.h)

    def inverse(self, V_target: np.ndarray) -> np.ndarray:
        """
        h_array⁻¹(V_target) — voltage to drive so that the array
        produces the linear-cell current.  Clamped to [V_min, V_max] of
        the original characterisation grid; out-of-range V_target values
        get the corresponding edge V_phys (no extrapolation).
        """
        V_target = np.asarray(V_target)
        # h is monotone non-decreasing → np.interp gives h⁻¹ when args swap.
        V_phys = np.interp(V_target, self.h, self.V_grid)
        return V_phys.astype(V_target.dtype, copy=False)

    @property
    def super_linearity_factor(self) -> float:
        """h(V_max) / V_max — diagnostic for log messages.  ~1 means linear,
        ~2 means cell+loading conduct twice as much as a linear cell at V_max."""
        return float(self.h[-1] / self.V_grid[-1]) if self.V_grid[-1] > 0 else 1.0


def estimate_r_access(
    table: "ArrayCharTable",
    Ik1: float, Vref: float, Tox: float, Tref: float,
    *, lrs_fraction: float = 0.5, v_min_frac: float = 0.3,
) -> Dict[str, float]:
    """Derive the effective per-cell series resistance from a SPICE array table.

    The 1T1R cell is a divider:  V_BL = V_memristor + I_cell * R_series,
    where the bare ReRAM obeys

        I = Ik1 * exp(-(Tox - T)/(Tox - Tref)) * sinh(V_memristor / Vref)

    The array table gives the SPICE-measured column current for an N x N array
    at uniform filament thickness T with every row driven at V_BL, so the
    per-cell current is I_col / N.  Inverting the ReRAM law recovers the
    voltage that actually lands on the memristor, and the remainder must be
    dropped across the series path (access transistor + BL driver + wire):

        R_series(T, V) = (V_BL - Vref * asinh(I_cell / (Ik1 * f(T)))) / I_cell

    This is exactly the ``R_access`` the weight -> conductance mapping needs
    (``G_cell = G_R / (1 + R_access * G_R)``), and it is strongly node
    dependent -- so it must never be left at a hardcoded default.

    R_series is only observable where the ReRAM is conducting hard enough for
    the series element to matter, so the estimate is taken over the LRS end of
    the T grid (top ``lrs_fraction``) and the upper part of the V sweep, and
    conductance-weighted (the compression only matters at LRS anyway).

    Returns {"R_access", "R_access_median", "R_access_lrs", "n_points"}.
    """
    T = np.asarray(table.T_grid, dtype=float)
    V = np.asarray(table.V_grid, dtype=float)
    I = np.asarray(table.I_primary, dtype=float)      # (nT, nV) column current
    N = int(table.N_primary)

    f = np.exp(-(Tox - T) / (Tox - Tref))             # conduction factor per T
    t_lo = T[0] + (1.0 - lrs_fraction) * (T[-1] - T[0])
    v_lo = V[0] + v_min_frac * (V[-1] - V[0])

    R_vals, W_vals, R_all = [], [], []
    for i, Ti in enumerate(T):
        for j, Vj in enumerate(V):
            if Vj <= 0:
                continue
            I_cell = abs(I[i, j]) / max(N, 1)
            if not np.isfinite(I_cell) or I_cell <= 0:
                continue
            s = I_cell / (Ik1 * f[i])                 # sinh(V_mem / Vref)
            V_mem = Vref * np.arcsinh(s)
            R = (Vj - V_mem) / I_cell
            if not np.isfinite(R) or R <= 0:
                continue                              # ideal / numerical noise
            R_all.append(R)
            if Ti >= t_lo and Vj >= v_lo:
                R_vals.append(R)
                W_vals.append(I_cell / Vj)            # weight by conductance
    if not R_vals:
        return {}
    R_vals = np.asarray(R_vals); W_vals = np.asarray(W_vals)
    return {
        "R_access": float(np.sum(R_vals * W_vals) / np.sum(W_vals)),
        "R_access_median": float(np.median(R_all)) if R_all else float("nan"),
        "R_access_lrs": float(np.median(R_vals)),
        "n_points": int(R_vals.size),
    }